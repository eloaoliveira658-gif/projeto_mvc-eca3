        <h2>Qual é o papel dos responsáveis?</h2>

        <p>
            Pais e responsáveis possuem um papel importante
            na educação e proteção de crianças e adolescentes
            durante o uso da internet.
        </p>

        <p>
            É importante acompanhar as atividades digitais,
            orientar sobre os riscos, respeitar a privacidade
            e manter um diálogo aberto, sem transformar
            a tecnologia em motivo de medo ou desconfiança.
        </p>

        <p>
            O ECA Digital reforça a responsabilidade
            compartilhada entre família, sociedade,
            Estado e plataformas digitais.
        </p>
    </section>

