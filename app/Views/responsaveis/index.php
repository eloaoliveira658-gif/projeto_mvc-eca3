    <section class="bloco-conteudo destaque">
        <h2>O que é supervisão parental?</h2>

        <p>
            É o acompanhamento realizado pelos
            responsáveis para ajudar a garantir
            uma experiência digital mais segura.
        </p>

        <p>
            O ECA Digital prevê ferramentas gratuitas
            de supervisão parental que devem ser
            acessíveis e fáceis de utilizar.
        </p>

        <p>Entre as possibilidades estão:</p>
        <ul class="lista-dicas">
            <li>Gerenciar configurações de privacidade.</li>
            <li>Acompanhar o tempo de utilização.</li>
            <li>Restringir compras e transações financeiras.</li>
            <li>Gerenciar configurações de comunicação.</li>
            <li>Controlar o compartilhamento de localização.</li>
            <li>Conhecer os recursos de segurança das plataformas.</li>
        </ul>
    </section>

