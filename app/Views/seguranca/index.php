    <section class="bloco-conteudo">
        <h2>Como se proteger?</h2>

        <div class="dica-item">
            <span class="numero-dica">01</span>
            <div>
                <h3>Proteja suas informações</h3>
                <p>
                    Evite divulgar endereço, telefone,
                    documentos e localização para desconhecidos.
                </p>
            </div>
        </div>

        <div class="dica-item">
            <span class="numero-dica">02</span>
            <div>
                <h3>Utilize senhas seguras</h3>
                <p>
                    Crie senhas diferentes para suas contas
                    e não compartilhe suas credenciais.
                </p>
            </div>
        </div>

        <div class="dica-item">
            <span class="numero-dica">03</span>
            <div>
                <h3>Configure sua privacidade</h3>
                <p>
                    Verifique quem pode visualizar suas
                    publicações e informações pessoais.
                </p>
            </div>
        </div>

        <div class="dica-item">
            <span class="numero-dica">04</span>
            <div>
                <h3>Desconfie de mensagens suspeitas</h3>
                <p>
                    Não clique em links desconhecidos e
                    não forneça dados em páginas duvidosas.
                </p>
            </div>
        </div>

        <div class="dica-item">
            <span class="numero-dica">05</span>
            <div>
                <h3>Respeite as outras pessoas</h3>
                <p>
                     Não compartilhe conteúdos ofensivos
                    nem exponha informações de terceiros.
                </p>
            </div>
        </div>

        <div class="dica-item">
            <span class="numero-dica">06</span>
            <div>
                <h3>Peça ajuda quando necessário</h3>
                <p>
                    Converse com um adulto de confiança
                    quando encontrar uma situação que
                    cause medo, desconforto ou insegurança.
                </p>
            </div>
        </div>
    </section>

    <section class="bloco-conteudo destaque">
        <h2>O que fazer em caso de violência digital?</h2>

        <ul class="lista-dicas">
            <li>Não responda às provocações ou ameaças.</li>
            <li>Guarde registros da situação para apresentar a um responsável.</li>
            <li>Bloqueie e denuncie a conta ou o conteúdo na plataforma.</li>
            <li>Procure um adulto de confiança.</li>
            <li>Se necessário, procure os órgãos de proteção competentes.</li>
        </ul>
    </section>

