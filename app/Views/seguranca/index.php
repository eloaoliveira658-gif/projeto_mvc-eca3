    <section class="bloco-conteudo">
        <h2>O que é segurança digital?</h2>

        <p>
            Segurança digital é o conjunto de cuidados
            e práticas que ajudam a proteger informações,
            dispositivos e pessoas durante o uso da internet.
        </p>

        <p>
            Ela envolve a proteção de dados pessoais,
            senhas, contas, imagens e informações
            compartilhadas em ambientes virtuais.
        </p>
    </section>

