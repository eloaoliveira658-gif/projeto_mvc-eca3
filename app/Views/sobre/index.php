            educativo voltado à proteção de crianças
            e adolescentes no ambiente digital.
        </p>

        <p>
            Nosso trabalho surgiu da necessidade
            de discutir os desafios enfrentados por
            crianças e adolescentes durante o uso
            das tecnologias e das plataformas digitais.
        </p>

        <p>
            Acreditamos que conhecer os próprios
            direitos é um passo importante para
            construir uma sociedade mais consciente,
            responsável e segura.
        </p>
    </section>

    <section class="bloco-conteudo destaque">
        <h2>Sobre o projeto ECA Digital</h2>

        <p>
            O projeto Crianças e Tecnologia tem como
            foco analisar a proteção de crianças e
            adolescentes no ambiente digital,
            considerando os desafios relacionados
            à exposição nas plataformas, ao cyberbullying,
            à desinformação e à privacidade.
        </p>

        <p>
            A proposta é desenvolver um site informativo
            e acessível que apresente orientações,
            direitos e responsabilidades com base
            no Estatuto da Criança e do Adolescente,
            no ECA Digital e na Lei Geral de Proteção
            de Dados Pessoais (LGPD).
        </p>

        <p>
            Também buscamos incentivar o diálogo
            entre estudantes, educadores, familiares
            e responsáveis sobre o uso consciente
            da tecnologia.
        </p>
    </section>

