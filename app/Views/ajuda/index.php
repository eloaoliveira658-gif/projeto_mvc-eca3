    <section class="bloco-conteudo destaque">
        <h2>Perguntas frequentes</h2>

        <details class="pergunta">
            <summary>O que é cyberbullying?</summary>
            <p>
                É a prática de intimidação, humilhação
                ou agressão realizada por meios digitais,
                como redes sociais e aplicativos.
            </p>
        </details>

        <details class="pergunta">
            <summary>Posso denunciar uma situação mesmo não sendo a vítima?</summary>
            <p>
                Sim. Qualquer pessoa pode comunicar
                uma suspeita de violação de direitos
                de crianças e adolescentes ao Disque 100.
            </p>
        </details>

        <details class="pergunta">
            <summary>O que fazer quando uma conta é invadida?</summary>
            <p>
                Procure recuperar a conta pelos canais
                oficiais da plataforma, altere as senhas
                comprometidas e informe um responsável.
            </p>
        </details>

        <details class="pergunta">
            <summary>O que fazer quando encontro um conteúdo inadequado?</summary>
            <p>
                Não compartilhe o conteúdo. Utilize
                os mecanismos de denúncia da plataforma
                e procure orientação de um adulto.
            </p>
        </details>

        <details class="pergunta">
            <summary>Este site recebe denúncias?</summary>
            <p>
                Não. Este é um projeto educativo.
                As denúncias devem ser realizadas
                nos canais oficiais e nas plataformas
                responsáveis.
            </p>
        </details>

