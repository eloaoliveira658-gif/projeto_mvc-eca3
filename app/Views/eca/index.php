    </section>

    <section class="bloco-conteudo destaque">
        <h2>O que é o ECA Digital?</h2>

        <p>
            O ECA Digital é o Estatuto Digital da Criança
            e do Adolescente, estabelecido pela Lei nº
            15.211, de 17 de setembro de 2025.
        </p>

        <p>
            A legislação estabelece medidas de proteção
            para crianças e adolescentes em ambientes
            digitais, como redes sociais, aplicativos,
            jogos eletrônicos e plataformas de vídeo.
        </p>

        <p>
            Seu objetivo é garantir mais segurança,
            privacidade e proteção de dados, além de
            prevenir situações de violência e exploração
            no ambiente virtual.
        </p>
    </section>

    <section class="bloco-conteudo">
        <h2>Por que essa lei é importante?</h2>

        <ul class="lista-dicas">
            <li>Ajuda a proteger a privacidade dos jovens.</li>
            <li>Estabelece responsabilidades para as plataformas digitais.</li>
            <li>Prevê medidas de segurança adequadas à idade.</li>
            <li>Valoriza a educação digital e o uso responsável da tecnologia.</li>
            <li>Fortalece a proteção contra conteúdos inadequados.</li>
        </ul>
    </section>

