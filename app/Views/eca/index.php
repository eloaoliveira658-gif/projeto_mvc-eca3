    <section class="bloco-conteudo">
        <h2>O que é o ECA?</h2>

        <p>
            O Estatuto da Criança e do Adolescente (ECA) é
            uma lei brasileira criada em 13 de julho de 1990,
            por meio da Lei nº 8.069.
        </p>

        <p>
            Ele estabelece os direitos e as garantias de
            crianças e adolescentes, reconhecendo que são
            pessoas em desenvolvimento e precisam de
            proteção integral.
        </p>

        <p>
            O ECA também determina responsabilidades
            para a família, a sociedade e o Estado na
            garantia desses direitos.
        </p>
    </section>

    <section class="bloco-conteudo">
        <h2>Quais são os principais objetivos?</h2>

        <div class="cards-conteudo">

            <article class="info-card">
                <i class="fa-solid fa-heart"></i>
                <h3>Proteção integral</h3>
                <p>
                    Garantir condições para o desenvolvimento
